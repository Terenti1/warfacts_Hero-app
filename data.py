# Вспомогательные функции
def get_all_tags():
    tags = set()
    for fact in FACTS_DATABASE:
        tags.update(fact["tags"])
    return sorted(list(tags))

def get_facts_by_tag(tag):
    return [fact for fact in FACTS_DATABASE if tag in fact["tags"]]

def get_fact_by_id(fact_id):
    for fact in FACTS_DATABASE:
        if fact["id"] == fact_id:
            return fact
    return None

def get_facts_count():
    return len(FACTS_DATABASE)